"""Generate a reproducible synthetic retail transaction dataset.

Every value produced here is synthetic. Products, prices (in INR), dates and customer IDs are
generated by this module and do not describe a real shop, real customers or real sales.

How a basket is built
---------------------
1. Each synthetic customer has two favourite "shopping missions" (for example breakfast or
   laundry) and a few habitual products. Some customers shop much more often than others.
2. A basket contains 0, 1 or 2 missions. A mission always adds its core product and adds each
   companion product with its own probability. This creates the controlled associations.
3. Habitual products are added with a small probability (repeat purchasing).
4. Independent "noise" purchases are drawn from overall product popularity, so baskets are not
   fixed combinations and some associations happen only by chance.

Only lists and dicts (never sets) are iterated, so the same seed always gives the same data.
"""
from __future__ import annotations

from dataclasses import dataclass
from datetime import date, timedelta

import numpy as np
import pandas as pd

COLUMNS = [
    "transaction_id",
    "transaction_date",
    "customer_id",
    "product_id",
    "product_name",
    "category",
    "quantity",
    "unit_price",
]


@dataclass(frozen=True)
class Product:
    product_id: str
    name: str
    category: str
    unit_price: float  # synthetic price in INR
    popularity: float  # relative weight for independent purchases


@dataclass(frozen=True)
class Mission:
    """A shopping occasion: one core product plus companions added with given probabilities."""

    name: str
    weight: float
    core: str
    companions: tuple[tuple[str, float], ...]


def _products(category: str, start: int, rows: list[tuple[str, float, float]]) -> list[Product]:
    return [
        Product(f"P{start + offset:03d}", name, category, price, popularity)
        for offset, (name, price, popularity) in enumerate(rows)
    ]


