MISSIONS_PER_BASKET = (0, 1, 2)
MISSION_COUNT_PROBABILITIES = (0.30, 0.55, 0.15)
FAVOURITE_MISSION_SHARE = 0.7
HABIT_PROBABILITY = 0.25
QUANTITIES = (1, 2, 3)
QUANTITY_PROBABILITIES = (0.78, 0.17, 0.05)
MAX_BASKET_SIZE = 15


def select_products(n_products: int | None = None) -> list[Product]:
    """Pick n products round-robin across categories so that every category stays represented."""
    if n_products is None:
        return list(CATALOG)
    categories: dict[str, list[Product]] = {}
    for product in CATALOG:
        categories.setdefault(product.category, []).append(product)
    if not len(categories) <= n_products <= len(CATALOG):
        raise ValueError(f"n_products must be between {len(categories)} and {len(CATALOG)}, got {n_products}")
    chosen: list[Product] = []
    depth = 0
    while len(chosen) < n_products:
        for products in categories.values():
            if depth < len(products) and len(chosen) < n_products:
                chosen.append(products[depth])
        depth += 1
    keep = {product.product_id for product in chosen}
    return [product for product in CATALOG if product.product_id in keep]


def active_missions(product_names: list[str]) -> list[Mission]:
    """Missions whose core product is available, with unavailable companions removed."""
    available = dict.fromkeys(product_names)
    missions = []
    for mission in MISSIONS:
        if mission.core in available:
            companions = tuple((name, p) for name, p in mission.companions if name in available)
            missions.append(Mission(mission.name, mission.weight, mission.core, companions))
    return missions


def generate_transactions(
    n_transactions: int = 8000,
    n_products: int | None = None,
    seed: int = 42,
    start_date: date = date(2025, 1, 1),
    days: int = 181,
    n_customers: int | None = None,
) -> pd.DataFrame:
    """Return a long-format DataFrame with one row per product in each synthetic transaction."""
    if n_transactions < 1:
        raise ValueError(f"n_transactions must be at least 1, got {n_transactions}")
    if days < 1:
        raise ValueError(f"days must be at least 1, got {days}")

    products = select_products(n_products)
    names = [product.name for product in products]
    index_of = {name: i for i, name in enumerate(names)}
    missions = active_missions(names)
    rng = np.random.default_rng(seed)

    popularity = np.array([product.popularity for product in products])
    popularity = popularity / popularity.sum()
    mission_weights = np.array([mission.weight for mission in missions])
    mission_weights = mission_weights / mission_weights.sum()

    n_customers = n_customers or max(50, n_transactions // 5)
    activity = rng.lognormal(mean=0.0, sigma=1.0, size=n_customers)
    activity = activity / activity.sum()
    favourite_count = min(2, len(missions))
    favourites = [rng.choice(len(missions), size=favourite_count, replace=False, p=mission_weights)
                  for _ in range(n_customers)]
    habits = [rng.choice(len(products), size=int(rng.integers(1, 4)), replace=False, p=popularity)
              for _ in range(n_customers)]

    calendar = [start_date + timedelta(days=offset) for offset in range(days)]
    day_weights = np.array([1.4 if day.weekday() >= 5 else 1.0 for day in calendar])
    day_weights = day_weights / day_weights.sum()
    customer_of = rng.choice(n_customers, size=n_transactions, p=activity)
    day_of = rng.choice(days, size=n_transactions, p=day_weights)

    baskets: list[list[int]] = []
    for t in range(n_transactions):
        customer = customer_of[t]
        basket: dict[int, None] = {}

        def add(product_index: int) -> None:
            if len(basket) < MAX_BASKET_SIZE:
                basket[product_index] = None

        for _ in range(int(rng.choice(MISSIONS_PER_BASKET, p=MISSION_COUNT_PROBABILITIES))):
            if missions and rng.random() < FAVOURITE_MISSION_SHARE:
                mission = missions[int(rng.choice(favourites[customer]))]
            else:
                mission = missions[int(rng.choice(len(missions), p=mission_weights))]
            add(index_of[mission.core])
            for name, probability in mission.companions:
                if rng.random() < probability:
                    add(index_of[name])
        for product_index in habits[customer]:
            if rng.random() < HABIT_PROBABILITY:
                add(int(product_index))
        n_independent = int(rng.poisson(1.2 if basket else 2.0))
        if not basket:
            n_independent = max(1, n_independent)
        for product_index in rng.choice(len(products), size=n_independent, p=popularity):
            add(int(product_index))
        baskets.append(list(basket))

    order = np.lexsort((np.arange(n_transactions), day_of))  # chronological IDs
    rows = []
    for rank, t in enumerate(order, start=1):
        for product_index in baskets[t]:
            product = products[product_index]
            rows.append(
                (
                    f"SYN-T{rank:06d}",
                    calendar[day_of[t]].isoformat(),
                    f"SYN-C{customer_of[t] + 1:05d}",
                    product.product_id,
                    product.name,
                    product.category,
                    int(rng.choice(QUANTITIES, p=QUANTITY_PROBABILITIES)),
                    float(product.unit_price),
                )
            )
    data = pd.DataFrame(rows, columns=COLUMNS)
    problems = validate_synthetic(data)
    if problems:
        raise ValueError("Generated data failed validation: " + "; ".join(problems))
    return data


def validate_synthetic(data: pd.DataFrame) -> list[str]:
    """Return a list of problems with a generated dataset (empty when it is valid)."""
    problems = []
    missing = [column for column in COLUMNS if column not in data.columns]
    if missing:
        return [f"missing columns: {missing}"]
    if data.empty:
        return ["dataset is empty"]
    if data[COLUMNS].isna().any().any():
        problems.append("dataset contains missing values")
    if (data["quantity"] < 1).any():
        problems.append("quantity must be at least 1")
    if (data["unit_price"] <= 0).any():
        problems.append("unit_price must be positive")
    if data.duplicated(["transaction_id", "product_id"]).any():
        problems.append("a product appears twice in the same transaction")
    if data.groupby("product_id")["product_name"].nunique().max() > 1:
        problems.append("a product_id maps to more than one product name")
    if data.groupby("product_name")["category"].nunique().max() > 1:
        problems.append("a product belongs to more than one category")
    if data.groupby("transaction_id")["customer_id"].nunique().max() > 1:
        problems.append("a transaction has more than one customer")
    if pd.to_datetime(data["transaction_date"], errors="coerce").isna().any():
        problems.append("invalid transaction dates")
    return problems


def add_data_quality_issues(
    data: pd.DataFrame,
    seed: int = 7,
    blank_names: float = 0.01,
    missing_ids: float = 0.005,
    case_variants: float = 0.02,
    extra_spaces: float = 0.02,
    duplicate_rows: float = 0.01,
) -> tuple[pd.DataFrame, dict[str, int]]:
    """Copy of generated data with known data-quality problems, for demos and validation tests.

    Each problem is applied to its own random set of rows, so the returned counts are exactly what
    the validator should report: blank product names, missing transaction IDs, upper-case variants
    of product names, names wrapped in extra spaces, duplicated rows and one extra column.
    """
    rng = np.random.default_rng(seed)
    messy = data.reset_index(drop=True).copy()
    rates = {"blank product names": blank_names, "missing transaction IDs": missing_ids,
             "capitalisation variants": case_variants, "extra spaces": extra_spaces,
             "duplicate rows": duplicate_rows}
    order = rng.permutation(len(messy))
    picks, start = {}, 0
    for name, rate in rates.items():
        size = int(round(rate * len(messy)))
        picks[name] = messy.index[np.sort(order[start:start + size])]
        start += size
    messy.loc[picks["blank product names"], "product_name"] = ""
    messy.loc[picks["missing transaction IDs"], "transaction_id"] = ""
    messy.loc[picks["capitalisation variants"], "product_name"] = \
        messy.loc[picks["capitalisation variants"], "product_name"].str.upper()
    messy.loc[picks["extra spaces"], "product_name"] = "  " + messy.loc[picks["extra spaces"], "product_name"] + " "
    duplicates = messy.loc[picks["duplicate rows"]]
    messy = pd.concat([messy, duplicates], ignore_index=True)
    messy["store_id"] = "SYN-STORE-01"
    counts = {name: len(rows) for name, rows in picks.items()}
    counts["extra columns"] = 1
    return messy, counts
