"""Overview: headline numbers, best sellers and calculated insights for the active dataset."""
from __future__ import annotations

import streamlit as st

from market_basket import plots
from market_basket.config import ALGORITHM_NAMES
from market_basket.data import summarize
from market_basket.insights import bundle_opportunities, key_insights, product_popularity
from ui import components as ui
from ui import state


def render() -> None:
    data = state.data()
    ui.page_header("Overview", "What customers buy, and which products they buy together.")
    ui.data_badge(data)
    stats = summarize(data)
    ui.metric_row([
        ("Transactions", f"{stats['transactions']:,}", "Valid transactions (baskets) after data cleaning."),
        ("Unique products", f"{stats['unique products']:,}", None),
        ("Average basket size", f"{stats['average basket size']:.2f}",
         "Average number of different products in a transaction."),
        ("Product categories", f"{stats['categories']}" if stats["categories"] else "Not provided",
         "Number of categories, if the data has a category column."),
    ])

    result, error = state.mining()
    popularity = product_popularity(data)
    left, right = st.columns([3, 2], gap="large")
    with left:
        ui.chart(plots.product_bar(popularity, top_n=10, title="Top-selling products"))
    with right:
        st.subheader("Key insights")
        if error:
            st.error(error)
        else:
            bundles = bundle_opportunities(result, state.best_sellers(), data.categories)
            for note in key_insights(data, result, popularity, bundles):
                st.markdown(f"- {ui.escape(note)}")
        st.subheader("Analysis summary")
        config = state.config()
        if result is not None:
            st.markdown(
                f"{len(result.rules):,} association rules from {len(result.frequent_itemsets):,} frequent itemsets, "
                f"using {ALGORITHM_NAMES[config.algorithm]} with minimum support {config.min_support:.1%}, "
                f"confidence {config.min_confidence:.0%} and lift {config.min_lift:.1f}."
                + (f" Ignored in rules, suggestions and bundles: {ui.escape(', '.join(config.exclude))}."
                   if config.exclude else "")
            )
        if "first date" in stats:
            st.markdown(f"Transactions from {stats['first date']} to {stats['last date']}.")
        if data.is_synthetic:
            st.caption("This dataset is synthetic: it was generated by BasketWise with known product associations "
                       "and does not describe real customers or sales.")

    st.subheader("How to use BasketWise")
    from ui.navigation import BUNDLES, DATA, EVALUATION, RECOMMEND, RULES

    steps = [
        (DATA, "1. Check your data", "Upload a CSV or use the demo data, and review the data-quality report."),
        (RULES, "2. Find associations", "Set thresholds and explore which products are bought together."),
        (RECOMMEND, "3. Try recommendations", "Build a basket and see suggested add-ons with the reason for each."),
        (BUNDLES, "4. Plan bundles", "Review potential bundles, cross-sell pairs and product groupings."),
        (EVALUATION, "5. Check the evidence", "Compare the recommendations with simply suggesting best sellers."),
    ]
    for column, (page, title, text) in zip(st.columns(len(steps)), steps, strict=True):
        with column.container(border=True, height="stretch"):
            st.markdown(f'<div class="bw-card-title">{title}</div><div class="bw-muted">{text}</div>',
                        unsafe_allow_html=True)
            st.page_link(page, label="Open", icon=":material/arrow_forward:")
