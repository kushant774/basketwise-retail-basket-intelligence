"""Settings & Data: data source, mining configuration, report downloads and application information."""
from __future__ import annotations

from datetime import datetime

import pandas as pd
import streamlit as st

from market_basket.config import MiningConfig
from market_basket.data import summarize
from market_basket.reporting import build_report, export_zip
from ui import components as ui
from ui import state


@st.cache_data(show_spinner="Preparing the report...", max_entries=4)
def _report_files(key: str, config: MiningConfig, evaluation_key: str, stamp: str, _data, _result, _evaluation):
    generated = datetime.fromisoformat(stamp)
    return (build_report(_data, _result, _evaluation, generated),
            export_zip(_data, _result, _evaluation, generated))


def render() -> None:
    data = state.data()
    config = state.config()
    ui.page_header("Settings & Data", "Data source, analysis settings, downloads and information about BasketWise.")
    left, right = st.columns(2, gap="large")
    with left.container(border=True):
        st.markdown('<div class="bw-card-title">Current dataset</div>', unsafe_allow_html=True)
        ui.data_badge(data)
        summary = pd.DataFrame([(key, str(value)) for key, value in summarize(data).items()],
                               columns=["measure", "value"])
        st.dataframe(summary, hide_index=True, width="stretch")
        if st.button("Reset to the bundled demo data", icon=":material/restart_alt:"):
            state.use_demo()
            ui.flash("Switched to the bundled synthetic demo data.")
            st.rerun()
    with right.container(border=True):
        st.markdown('<div class="bw-card-title">Mining configuration</div>', unsafe_allow_html=True)
        settings = pd.DataFrame(
            [("Algorithm", "FP-Growth" if config.algorithm == "fpgrowth" else "Apriori"),
             ("Minimum support", f"{config.min_support:.1%}"),
             ("Minimum confidence", f"{config.min_confidence:.0%}"),
             ("Minimum lift", f"{config.min_lift:.2f}"),
             ("Maximum products per rule", str(config.max_len or "No limit")),
             ("Ignored products", ", ".join(config.exclude) or "None")],
            columns=["setting", "value"])
        st.dataframe(settings, hide_index=True, width="stretch")
        st.caption("Change these on the Association Rules page.")
        if st.button("Reset settings to defaults", icon=":material/settings_backup_restore:"):
            state.set_config(MiningConfig())
            ui.flash("Mining settings were reset to the defaults.")
            st.rerun()

    st.subheader("Download report")
    result, error = state.mining()
    if error:
        st.error(f"The report needs valid mining settings: {error}", icon=":material/error:")
    else:
        evaluation, stale = state.latest_evaluation()
        use_evaluation = evaluation if evaluation is not None and not stale else None
        stamp = datetime.now().replace(second=0, microsecond=0).isoformat()
        evaluation_key = repr(use_evaluation.settings) if use_evaluation is not None else ""
        report, archive = _report_files(state.source_key(), config, evaluation_key, stamp,
                                        data, result, use_evaluation)
        st.caption("The report summarises the data, validation, rules, opportunities and"
                   + (" the latest evaluation." if use_evaluation is not None
                      else " (run the Evaluation Lab first to include evaluation results)."))
        a, b = st.columns(2)
        a.download_button("Download report (Markdown)", report, "basketwise_report.md", "text/markdown",
                          icon=":material/description:", type="primary")
        b.download_button("Download all results (ZIP of CSV files)", archive, "basketwise_results.zip",
                          "application/zip", icon=":material/folder_zip:")

    st.subheader("About BasketWise")
    st.markdown(
        "- **What it does**: validates transaction data, finds products bought together, recommends add-on "
        "products with explanations, suggests potential bundles and checks recommendations against a "
        "best-seller baseline.\n"
        "- **Algorithms**: frequent itemsets (Apriori and FP-Growth) and association rules come from the open-source "
        "[mlxtend](https://rasbt.github.io/mlxtend/) library. BasketWise's own code handles data validation, "
        "settings, ranking, recommendations, fallback logic, evaluation, insights, charts and reports.\n"
        "- **Other libraries**: pandas and NumPy (data), Plotly (charts), NetworkX (product groups), Streamlit (app).\n"
        "- **Your data**: uploaded files are processed in memory for this app session and are not written to disk "
        "by BasketWise.\n"
        "- **Demo data**: synthetic, generated by `scripts/generate_data.py` with a fixed seed. It is not real "
        "customer or sales data."
    )
    st.caption("BasketWise runs locally. Associations describe observed co-occurrence, not causation; test "
               "opportunities before acting on them.")
